#!/usr/bin/env bun
/**
 * Generates the Vercel deployment output for PiGigz (Build Output API).
 *
 * Why this exists: the previous deployment only published the static
 * client (`outputDirectory: client/dist`), so the page loaded but every
 * `POST /actions` returned Vercel's 404 — there was no server function
 * running the marketplace actions. This script is run as the last step
 * of `bun run build` and produces `.vercel/output/`:
 *
 *   static/                     ← copy of client/dist (the page + assets)
 *   functions/actions.func/     ← Node serverless function bundling
 *                                 server/src/vercel-entry.ts, which hosts
 *                                 the SAME actions, privileged Pi payment
 *                                 handlers and Drizzle schema, backed by
 *                                 a libSQL (Turso) database
 *   config.json                 ← routes: /actions → the function,
 *                                 everything else → static files with an
 *                                 SPA fallback, plus the security headers
 *                                 that used to live in vercel.json
 *
 * It also regenerates `server/src/migrations-data.generated.ts` from the
 * SQL files in `drizzle/` (in journal order) so the function can apply
 * the schema to a fresh hosted database on cold start.
 *
 * Run standalone with:  bun ./server/gen-vercel.mjs
 */
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, ".vercel", "output");
const funcDir = join(outDir, "functions", "actions.func");

function fail(message) {
  console.error(`gen-vercel: ${message}`);
  process.exit(1);
}

/* ------------------------------------------------------------------ */
/* 1. Embed the drizzle migrations for the serverless entry.           */
/* ------------------------------------------------------------------ */

const journalPath = join(root, "drizzle", "meta", "_journal.json");
if (!existsSync(journalPath)) fail(`missing ${journalPath}`);
const journal = JSON.parse(readFileSync(journalPath, "utf8"));
const migrations = journal.entries.map((entry) => {
  const sqlPath = join(root, "drizzle", `${entry.tag}.sql`);
  if (!existsSync(sqlPath)) fail(`missing migration file ${sqlPath}`);
  return { tag: entry.tag, sql: readFileSync(sqlPath, "utf8") };
});
const migrationsModule = `// GENERATED by server/gen-vercel.mjs from drizzle/*.sql — do not edit by hand.
// The Vercel serverless entry applies these, in order, to the hosted
// libSQL database on cold start (tracked in __pigigz_migrations).
export interface MigrationSql {
  readonly tag: string;
  readonly sql: string;
}
export const MIGRATIONS: readonly MigrationSql[] = [
${migrations.map((m) => `  { tag: ${JSON.stringify(m.tag)}, sql: ${JSON.stringify(m.sql)} },`).join("\n")}
];
`;
writeFileSync(
  join(root, "server", "src", "migrations-data.generated.ts"),
  migrationsModule,
);
console.log(
  `gen-vercel: embedded ${migrations.length} migrations into server/src/migrations-data.generated.ts`,
);

/* ------------------------------------------------------------------ */
/* 2. Fresh output directory.                                          */
/* ------------------------------------------------------------------ */

rmSync(outDir, { recursive: true, force: true });
mkdirSync(funcDir, { recursive: true });

/* ------------------------------------------------------------------ */
/* 3. Static site: client/dist → .vercel/output/static                 */
/* ------------------------------------------------------------------ */

const clientDist = join(root, "client", "dist");
if (!existsSync(join(clientDist, "index.html"))) {
  fail("client/dist/index.html not found — run build:client first");
}
cpSync(clientDist, join(outDir, "static"), { recursive: true });
console.log("gen-vercel: copied client/dist to .vercel/output/static");

/* ------------------------------------------------------------------ */
/* 4. The /actions serverless function.                                */
/*                                                                     */
/* `libsql` (the native binding @libsql/client loads for file:        */
/* databases) stays external: its JS loader resolves the platform      */
/* binary package `@libsql/<target>` at runtime, so the runtime        */
/* closure is copied next to the bundle below. Remote libSQL/Turso     */
/* URLs never touch the native binding, but the module is imported     */
/* eagerly by @libsql/client, so the files must exist either way.      */
/* ------------------------------------------------------------------ */

execFileSync(
  "bun",
  [
    "build",
    "./src/vercel-entry.ts",
    "--target=node",
    "--format=esm",
    "--external",
    "libsql",
    `--outfile=${join(funcDir, "index.js")}`,
  ],
  { cwd: join(root, "server"), stdio: "inherit" },
);
writeFileSync(join(funcDir, "package.json"), '{"type":"module"}\n');
writeFileSync(
  join(funcDir, ".vc-config.json"),
  `${JSON.stringify(
    {
      runtime: "nodejs22.x",
      handler: "index.js",
      launcherType: "Nodejs",
      shouldAddHelpers: true,
      maxDuration: 60,
    },
    null,
    2,
  )}\n`,
);

const nativeClosure = ["libsql", "@neon-rs/load", "detect-libc"];
for (const pkg of nativeClosure) {
  const src = join(root, "node_modules", pkg);
  if (!existsSync(src)) {
    fail(
      `node_modules/${pkg} not found — the @libsql/client native loader needs it; run bun install first`,
    );
  }
  cpSync(src, join(funcDir, "node_modules", pkg), { recursive: true });
}
const libsqlScope = join(root, "node_modules", "@libsql");
for (const name of readdirSync(libsqlScope)) {
  if (/^(linux|darwin|win32)-/.test(name)) {
    cpSync(join(libsqlScope, name), join(funcDir, "node_modules", "@libsql", name), {
      recursive: true,
    });
  }
}
console.log("gen-vercel: bundled actions function into .vercel/output/functions/actions.func");

/* ------------------------------------------------------------------ */
/* 5. Routes + headers (Build Output API config).                      */
/*                                                                     */
/* The header set is the one that previously lived in vercel.json: a   */
/* CSP tuned to what the page loads (Pi SDK, Google Fonts, map tiles,  */
/* Pi Platform API + Testnet horizon) and frame-ancestors limited to   */
/* Pi Sandbox / Pi Browser.                                            */
/* ------------------------------------------------------------------ */

const headers = {
  "Content-Security-Policy":
    "default-src 'self'; script-src 'self' 'unsafe-inline' https://sdk.minepi.com; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' data: https://fonts.gstatic.com; img-src 'self' data: blob: https://external.xx.fbcdn.net https://clarity.maptiles.arcgis.com https://*.tiles.virtualearth.net; connect-src 'self' https://api.minepi.com https://api.testnet.minepi.com https://sdk.minepi.com https://external.xx.fbcdn.net https://clarity.maptiles.arcgis.com https://*.tiles.virtualearth.net; worker-src 'self' blob:; child-src 'self' blob:; frame-ancestors 'self' https://sandbox.minepi.com https://minepi.com https://*.minepi.com; base-uri 'self'; form-action 'self'",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
};

const config = {
  version: 3,
  routes: [
    { src: "/(.*)", headers, continue: true },
    { src: "/actions", dest: "/actions" },
    { handle: "filesystem" },
    { src: "/(.*)", dest: "/index.html", status: 200 },
  ],
};
writeFileSync(join(outDir, "config.json"), `${JSON.stringify(config, null, 2)}\n`);
console.log("gen-vercel: wrote .vercel/output/config.json");
console.log("gen-vercel: done — deploy reads .vercel/output (Build Output API)");
